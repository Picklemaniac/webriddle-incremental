import { mkdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

interface Label {
    readonly center: number;
    readonly top: number;
}

const commons = 'https://upload.wikimedia.org/wikipedia/commons';
const sources = {
    semaphore: `${commons}/a/a4/Semaphore_Signals_A-Z.svg`,
    clock: `${commons}/5/58/Clock_12-01.svg`,
    present: `${commons}/9/9d/Red_Christmas_present_on_white_background.jpg`,
};
const outputFile = 'src/content/act-one/generated/props.ts';
const chartDensity = 96;
const figureBox = { width: 236, height: 174 };
const figureScale = 0.42;
const presentWidth = 320;
const lineColour = 216;
const clockFaceColour = '#161616';
const clockLineColour = '#d8d8d8';

const [semaphoreChart, clockSvg, presentJpeg] = await Promise.all([download(sources.semaphore), download(sources.clock), download(sources.present)]);
const figures = await semaphoreFigures(semaphoreChart);
const present = await sharp(presentJpeg).resize(presentWidth).jpeg({ quality: 78, mozjpeg: true }).toBuffer({ resolveWithObject: true });

const lines = [
    '// Generated by tools/build-props.ts from Wikimedia Commons. Do not edit by hand.',
    '// Semaphore Signals A-Z.svg (CC0), Clock 12-01.svg by Micthev (public domain),',
    '// Red Christmas present on white background.jpg by Petr Kratochvil (CC0).',
    `export const semaphoreFigure = { width: ${figures.width}, height: ${figures.height} } as const;`,
    'export const semaphoreFigures: Readonly<Record<string, string>> = {',
    ...figures.images.map(([letter, png]) => `    ${letter}: 'data:image/png;base64,${png}',`),
    '};',
    `export const clockFace = ${JSON.stringify(clockTemplate(clockSvg.toString('utf8')))};`,
    `export const presentPhoto = { src: 'data:image/jpeg;base64,${present.data.toString('base64')}', width: ${present.info.width}, height: ${present.info.height} } as const;`,
];
await mkdir('src/content/act-one/generated', { recursive: true });
await writeFile(outputFile, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${figures.images.length} semaphore figures, the clock face and the present photo to ${outputFile}.`);

async function download(url: string): Promise<Buffer> {
    const response = await fetch(url, { headers: { 'User-Agent': 'webriddle-incremental-asset-fetch/1.0' } });
    if (!response.ok) throw new Error(`Could not download ${url}: ${response.status}`);
    return Buffer.from(await response.arrayBuffer());
}

async function semaphoreFigures(chart: Buffer): Promise<{ width: number; height: number; images: [string, string][] }> {
    const flattened = await sharp(chart, { density: chartDensity }).flatten({ background: '#ffffff' }).png().toBuffer();
    const { data, info } = await sharp(flattened).raw().toBuffer({ resolveWithObject: true });
    const isLabel = (x: number, y: number): boolean => {
        const index = (y * info.width + x) * info.channels;
        const [red, green, blue] = [data[index]!, data[index + 1]!, data[index + 2]!];
        return blue > 90 && blue - red > 60 && blue - green > 20;
    };
    const labels: Label[] = [];
    for (const band of runs(info.height, (y) => Array.from({ length: info.width }, (_, x) => x).some((x) => isLabel(x, y)))) {
        for (const cluster of runs(info.width, (x) => band.some((y) => isLabel(x, y)), 20)) {
            labels.push({ center: (cluster[0]! + cluster.at(-1)!) / 2, top: band[0]! });
        }
    }
    if (labels.length < 26) throw new Error(`Found ${labels.length} semaphore labels, expected at least 26.`);
    const width = Math.round(figureBox.width * figureScale);
    const height = Math.round(figureBox.height * figureScale);
    const images: [string, string][] = [];
    for (const [index, label] of labels.slice(0, 26).entries()) {
        const figure = await sharp(flattened)
            .extract({ left: Math.round(label.center - figureBox.width / 2), top: label.top - figureBox.height - 4, width: figureBox.width, height: figureBox.height })
            .resize(width, height)
            .removeAlpha()
            .raw()
            .toBuffer();
        const png = await sharp(lightOnTransparent(figure), { raw: { width, height, channels: 4 } }).png({ palette: true, colours: 32 }).toBuffer();
        images.push([String.fromCharCode(97 + index), png.toString('base64')]);
    }
    return { width, height, images };
}

function lightOnTransparent(pixels: Buffer): Buffer {
    const output = Buffer.alloc((pixels.length / 3) * 4);
    for (let pixel = 0; pixel < pixels.length / 3; pixel++) {
        const channels = [pixels[pixel * 3]!, pixels[pixel * 3 + 1]!, pixels[pixel * 3 + 2]!];
        const alpha = Math.max(...channels.map((channel) => 255 - channel)) / 255;
        if (alpha === 0) continue;
        const colour = channels.map((channel) => Math.round((channel - 255 * (1 - alpha)) / alpha));
        const isLine = Math.max(...colour) - Math.min(...colour) < 60;
        output.set([...(isLine ? [lineColour, lineColour, lineColour] : colour), Math.round(alpha * 255)], pixel * 4);
    }
    return output;
}

function runs(length: number, included: (position: number) => boolean, gap = 1): number[][] {
    const result: number[][] = [];
    let current: number[] = [];
    let last = -Infinity;
    for (let position = 0; position < length; position++) {
        if (!included(position)) continue;
        if (position - last > gap && current.length > 0) {
            result.push(current);
            current = [];
        }
        current.push(position);
        last = position;
    }
    if (current.length > 0) result.push(current);
    return result;
}

function clockTemplate(svg: string): string {
    const template = svg
        .replace(/<\?xml[^>]*>\s*/, '')
        .replace(/<svg[^>]*>/, (tag) => `${tag}<circle cx="0" cy="0" r="98" fill="${clockFaceColour}" stroke="${clockLineColour}" stroke-width="3"/>`)
        .replaceAll('"black"', `"${clockLineColour}"`)
        .replace('transform="rotate(6)"', 'transform="rotate({minute})"')
        .replace('transform="rotate(0.5)"', 'transform="rotate({hour})"')
        .replace(/\s+/g, ' ');
    if (!template.includes('{minute}') || !template.includes('{hour}')) throw new Error('The clock hands were not found.');
    return template;
}
